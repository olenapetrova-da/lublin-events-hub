// scripts/generate-adr-index.js
//
// Generate docs/adr/ADR-0000-index.md from individual ADR markdown files.
//
// Assumptions:
// - ADR files live under DOCS_ROOT (default: "docs/adr").
// - Each ADR has a heading and metadata block like:
//
//   # ADR-0005 – Data model — raw_events → events
//
//   *Status:* Accepted (concept; implementation differs)
//   *Date:* 2025-11-10
//   *Applies to:* LEHv1, LEHv2, S1
//   *Superseded by:* ADR-0015
//
// Rules:
// - Status in index is the bare word without bracket comments (e.g. "Accepted").
// - "Applies to" and "Superseded by" are printed as-is (raw text, no parsing).
// - ADR-0000-index.md itself is generated and not read as input.

const fs = require("node:fs");
const path = require("node:path");

const DOCS_ROOT = (process.env.DOCS_ROOT || "docs/adr")
  .replace(/\\/g, "/")
  .replace(/\/+$/, ""); // strip trailing slash

const INDEX_FILE = path.join(DOCS_ROOT, "ADR-0000-index.md");

function readDirSafe(dir) {
  try {
    return fs.readdirSync(dir, { withFileTypes: true });
  } catch (e) {
    console.error(`Cannot read directory ${dir}: ${e.message}`);
    process.exit(1);
  }
}

// Parse ADR metadata from markdown content
function parseAdrMetadata(markdown, fileName) {
  if (!markdown || typeof markdown !== "string") {
    return null;
  }

  // H1: "# ADR-0005 – Title" or "# ADR-0005: Title"
  const h1Match = markdown.match(
    /^#\s*(ADR-\d+)\s*[–\-:]\s*(.+)$/m
  );
  const adrId = h1Match ? h1Match[1].trim() : "";
  let adrTitle = h1Match ? h1Match[2].trim() : "";

  if (!adrId) {
    return null;
  }

  if (!adrTitle) {
    // fallback title from file name
    adrTitle = fileName.replace(/\.[^.]+$/, "");
  }

  function extract(field) {
    const re = new RegExp(
      `^\\*${field}:\\*\\s*(.+)$`,
      "mi"
    );
    const m = markdown.match(re);
    return m ? m[1].trim() : "";
  }

  const statusRaw = extract("Status");
  const status = statusRaw.split("(")[0].trim(); // drop comments in brackets

  const date = extract("Date");
  const appliesRaw = extract("Applies to");
  const supersededRaw = extract("Superseded by");
  const supersededBy = supersededRaw
    .split("(")[0]
    .trim();

  return {
    adrId,
    adrTitle,
    status,
    date,
    appliesRaw,
    supersededBy,
  };
}

function escapeCell(text) {
  if (!text) return "";
  // Escape pipe characters so they don't break the table
  return String(text).replace(/\|/g, "\\|");
}

function generateIndexMarkdown(rows) {
  const headerLines = [
    "# ADR-0000 – Index of architecture decisions",
    "",
    "This file summarizes key ADRs and their applicability to LEHv1 (Make + Sheets + Apps Script) and LEHv2 (n8n + Supabase + Telegram).",
    "",
    "| ID | Title | Date | Status | Applies to | Superseded by |",
    "|----|-------|------|--------|------------|----------------|",
  ];

  const rowLines = rows.map((r) => {
    return (
      "| " +
      escapeCell(r.adrId) +
      " | " +
      escapeCell(r.adrTitle) +
      " | " +
      escapeCell(r.date) +
      " | " +
      escapeCell(r.status) +
      " | " +
      escapeCell(r.appliesRaw) +
      " | " +
      escapeCell(r.supersededBy) +
      " |"
    );
  });

  const footerLines = [
    "",
    "> Note: This file is generated by `scripts/generate-adr-index.js`. Do not edit it by hand.",
    "",
  ];

  return (
    headerLines.join("\n") +
    "\n" +
    rowLines.join("\n") +
    "\n" +
    footerLines.join("\n")
  );
}

function main() {
  const dirEntries = readDirSafe(DOCS_ROOT);

  const adrFiles = dirEntries
    .filter((d) => d.isFile())
    .map((d) => d.name)
    .filter((name) => {
      if (!name.startsWith("ADR-")) return false;
      if (!name.endsWith(".md")) return false;
      if (name === "ADR-0000-index.md") return false;
      return true;
    });

  if (adrFiles.length === 0) {
    console.warn(
      `No ADR files found under ${DOCS_ROOT} (excluding ADR-0000-index.md).`
    );
  }

  const rows = [];

  for (const fileName of adrFiles) {
    const fullPath = path.join(DOCS_ROOT, fileName);
    let content = "";
    try {
      content = fs.readFileSync(fullPath, "utf8");
    } catch (e) {
      console.warn(
        `Cannot read ADR file ${fullPath}: ${e.message}`
      );
      continue;
    }

    const meta = parseAdrMetadata(content, fileName);
    if (!meta) {
      console.warn(
        `Skipping ${fullPath}: no recognizable ADR metadata`
      );
      continue;
    }
    rows.push(meta);
  }

  // Sort by numeric ADR ID (ADR-0001, ADR-0002, ...)
  rows.sort((a, b) => {
    const na = parseInt(a.adrId.slice(4), 10);
    const nb = parseInt(b.adrId.slice(4), 10);
    if (Number.isNaN(na) || Number.isNaN(nb)) {
      return a.adrId.localeCompare(b.adrId);
    }
    return na - nb;
  });

  const md = generateIndexMarkdown(rows);

  try {
    fs.writeFileSync(INDEX_FILE, md, "utf8");
    console.log(
      `ADR index written to ${INDEX_FILE} (${rows.length} ADRs).`
    );
  } catch (e) {
    console.error(
      `Failed to write index file ${INDEX_FILE}: ${e.message}`
    );
    process.exit(1);
  }
}

main();
